# =========================================================
# SUMO CONFIG PATH
# =========================================================

def get_sumo_config(
    scenario_name
):
    """
    Return the actual SUMO configuration
    generated by scenario_manager.py.
    """

    config = (
        SCENARIO_ROOT
        / scenario_name
        / "simulation.sumocfg"
    )

    if not config.exists():

        raise FileNotFoundError(
            f"SUMO configuration not found:\n{config}"
        )

    return config


# =========================================================
# SAFE FLOAT
# =========================================================

def safe_float(value):

    try:

        return float(value)

    except Exception:

        return 0.0


# =========================================================
# CURRENT VEHICLES
# =========================================================

def get_active_vehicle_count():

    if not traci.isLoaded():

        return 0

    try:

        return len(
            traci.vehicle.getIDList()
        )

    except Exception:

        return 0


# =========================================================
# WAITING TIME
# =========================================================

def get_waiting_time():

    if not traci.isLoaded():

        return 0.0

    total = 0.0

    try:

        vehicles = (
            traci.vehicle.getIDList()
        )

        for vehicle_id in vehicles:

            total += safe_float(
                traci.vehicle.getWaitingTime(
                    vehicle_id
                )
            )

    except Exception:

        return total

    return total


# =========================================================
# QUEUE
# =========================================================

def get_queue_length():

    if not traci.isLoaded():

        return 0

    queue = 0

    try:

        vehicles = (
            traci.vehicle.getIDList()
        )

        for vehicle_id in vehicles:

            speed = safe_float(
                traci.vehicle.getSpeed(
                    vehicle_id
                )
            )

            if speed < 0.1:

                queue += 1

    except Exception:

        return queue

    return queue


# =========================================================
# AVERAGE SPEED
# =========================================================

def get_average_speed():

    if not traci.isLoaded():

        return 0.0

    speeds = []

    try:

        vehicles = (
            traci.vehicle.getIDList()
        )

        for vehicle_id in vehicles:

            speeds.append(
                safe_float(
                    traci.vehicle.getSpeed(
                        vehicle_id
                    )
                )
            )

    except Exception:

        return 0.0

    if not speeds:

        return 0.0

    return float(
        np.mean(speeds)
    )


# =========================================================
# RUN ONE SCENARIO
# =========================================================

def run_scenario(
    scenario_name
):

    print()
    print("=" * 70)
    print(
        f"Validating scenario: {scenario_name}"
    )
    print("=" * 70)

    config = get_sumo_config(
        scenario_name
    )

    print()
    print(
        "Configuration:"
    )
    print(config)
    print()

    if traci.isLoaded():

        try:
            traci.close()
        except Exception:
            pass

    start_time = time.time()

    # -----------------------------------------------------
    # Statistics
    # -----------------------------------------------------

    total_inserted = 0
    total_arrived = 0

    waiting_values = []
    queue_values = []
    speed_values = []
    active_values = []

    simulation_steps = 0
    final_simulation_time = 0.0

    # -----------------------------------------------------
    # Start SUMO
    # -----------------------------------------------------

    try:

        traci.start(
            [
                EnvironmentConfig.SUMO_BINARY,
                "-c",
                str(config),
                "--start",
                "--quit-on-end"
            ]
        )

        # -------------------------------------------------
        # Simulation loop
        # -------------------------------------------------

        while True:

            traci.simulationStep()

            simulation_steps += 1

            # ---------------------------------------------
            # Current simulation time
            # ---------------------------------------------

            current_time = safe_float(
                traci.simulation.getTime()
            )

            final_simulation_time = (
                current_time
            )

            # ---------------------------------------------
            # IMPORTANT:
            #
            # getDepartedNumber() is PER STEP.
            #
            # Therefore we ADD it.
            # ---------------------------------------------

            try:

                total_inserted += (
                    traci.simulation
                    .getDepartedNumber()
                )

            except Exception:

                pass

            # ---------------------------------------------
            # Arrivals are also per step
            # ---------------------------------------------

            try:

                total_arrived += (
                    traci.simulation
                    .getArrivedNumber()
                )

            except Exception:

                pass

            # ---------------------------------------------
            # Traffic metrics
            # ---------------------------------------------

            active_values.append(
                get_active_vehicle_count()
            )

            waiting_values.append(
                get_waiting_time()
            )

            queue_values.append(
                get_queue_length()
            )

            speed_values.append(
                get_average_speed()
            )

            # ---------------------------------------------
            # End simulation
            # ---------------------------------------------

            if current_time >= SIMULATION_END:

                break

            # ---------------------------------------------
            # Safety guard
            # ---------------------------------------------

            if simulation_steps > (
                SIMULATION_END + 100
            ):

                break

        # =================================================
        # FINAL METRICS
        # =================================================

        average_active = (
            float(np.mean(active_values))
            if active_values
            else 0.0
        )

        average_waiting = (
            float(np.mean(waiting_values))
            if waiting_values
            else 0.0
        )

        maximum_waiting = (
            float(np.max(waiting_values))
            if waiting_values
            else 0.0
        )

        average_queue = (
            float(np.mean(queue_values))
            if queue_values
            else 0.0
        )

        maximum_queue = (
            float(np.max(queue_values))
            if queue_values
            else 0.0
        )

        average_speed = (
            float(np.mean(speed_values))
            if speed_values
            else 0.0
        )

        maximum_speed = (
            float(np.max(speed_values))
            if speed_values
            else 0.0
        )

        minimum_speed = (
            float(np.min(speed_values))
            if speed_values
            else 0.0
        )

        final_active = (
            get_active_vehicle_count()
        )

        # -------------------------------------------------
        # Traffic lights
        # -------------------------------------------------

        try:

            traffic_light_count = len(
                traci.trafficlight.getIDList()
            )

        except Exception:

            traffic_light_count = 0

        # -------------------------------------------------
        # Runtime
        # -------------------------------------------------

        runtime = (
            time.time()
            - start_time
        )

        # =================================================
        # RESULT
        # =================================================

        result = {

            "scenario": scenario_name,

            "sumo_config": str(config),

            "simulation_valid": True,

            "simulation_time": final_simulation_time,

            "simulation_steps": simulation_steps,

            "vehicles_inserted": total_inserted,

            "vehicles_arrived": total_arrived,

            "vehicles_active_final": final_active,

            "average_active_vehicles": average_active,

            "average_waiting_time": average_waiting,

            "maximum_waiting_time": maximum_waiting,

            "average_queue_length": average_queue,

            "maximum_queue_length": maximum_queue,

            "average_speed": average_speed,

            "maximum_speed": maximum_speed,

            "minimum_speed": minimum_speed,

            "traffic_light_count": traffic_light_count,

            "simulation_runtime_seconds": runtime

        }

        return result

    finally:

        if traci.isLoaded():

            try:
                traci.close()
            except Exception:
                pass


