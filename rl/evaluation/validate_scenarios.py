# SAVE CSV
# =========================================================

def save_csv(
    results
):

    fields = [

        "scenario",

        "sumo_config",

        "simulation_valid",

        "simulation_time",

        "simulation_steps",

        "vehicles_inserted",

        "vehicles_arrived",

        "vehicles_active_final",

        "average_active_vehicles",

        "average_waiting_time",

        "maximum_waiting_time",

        "average_queue_length",

        "maximum_queue_length",

        "average_speed",

        "maximum_speed",

        "minimum_speed",

        "traffic_light_count",

        "simulation_runtime_seconds",

        "error_type",

        "error"

    ]

    with open(
        CSV_FILE,
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fields
        )

        writer.writeheader()

        for result in results:

            row = {}

            for field in fields:

                row[field] = result.get(
                    field,
                    ""
                )

            writer.writerow(row)

    print()
    print(
        "CSV saved to:"
    )
    print(CSV_FILE)


