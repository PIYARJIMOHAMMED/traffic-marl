# =========================================================
# DUPLICATE CHECK
# =========================================================

def duplicate_check(
    results
):

    valid = [

        r

        for r in results

        if r.get(
            "simulation_valid",
            False
        )

    ]

    signatures = {}

    for result in valid:

        signature = (

            result[
                "vehicles_inserted"
            ],

            result[
                "vehicles_arrived"
            ],

            round(
                result[
                    "average_waiting_time"
                ],
                4
            ),

            round(
                result[
                    "average_queue_length"
                ],
                4
            ),

            round(
                result[
                    "average_speed"
                ],
                4
            )

        )

        signatures.setdefault(
            signature,
            []
        ).append(
            result["scenario"]
        )

    duplicates = [

        group

        for group in signatures.values()

        if len(group) > 1

    ]

    print()
    print("=" * 70)
    print(
        "SCENARIO DIFFERENCE CHECK"
    )
    print("=" * 70)
    print()

    if not duplicates:

        print(
            "[PASS] No exact metric duplicates."
        )

    else:

        print(
            "[WARNING] Identical metric groups:"
        )

        for group in duplicates:

            print(
                "  ",
                group
            )

    return duplicates


# =========================================================
# DEMAND ANALYSIS
# =========================================================

def demand_analysis(
    results
):

    valid = [

        r

        for r in results

        if r.get(
            "simulation_valid",
            False
        )

    ]

    if not valid:

        print(
            "[WARNING] No valid scenarios."
        )

        return

    baseline = None

    for result in valid:

        if result[
            "scenario"
        ] == "baseline":

            baseline = result

            break

    if baseline is None:

        print(
            "[WARNING] Baseline unavailable."
        )

        return

    base_inserted = baseline[
        "vehicles_inserted"
    ]

    base_waiting = baseline[
        "average_waiting_time"
    ]

    base_queue = baseline[
        "average_queue_length"
    ]

    base_speed = baseline[
        "average_speed"
    ]

    print()
    print("=" * 90)
    print(
        "CHANGE FROM BASELINE"
    )
    print("=" * 90)
    print()

    print(
        f"{'Scenario':<22}"
        f"{'Vehicles %':>16}"
        f"{'Waiting %':>16}"
        f"{'Queue %':>16}"
        f"{'Speed %':>16}"
    )

    print("-" * 90)

    for result in valid:

        inserted = result[
            "vehicles_inserted"
        ]

        waiting = result[
            "average_waiting_time"
        ]

        queue = result[
            "average_queue_length"
        ]

        speed = result[
            "average_speed"
        ]

        inserted_delta = (

            (
                inserted
                - base_inserted
            )
            / base_inserted
            * 100

            if base_inserted
            else 0.0

        )

        waiting_delta = (

            (
                waiting
                - base_waiting
            )
            / base_waiting
            * 100

            if base_waiting
            else 0.0

        )

        queue_delta = (

            (
                queue
                - base_queue
            )
            / base_queue
            * 100

            if base_queue
            else 0.0

        )

        speed_delta = (

            (
                speed
                - base_speed
            )
            / base_speed
            * 100

            if base_speed
            else 0.0

        )

        print(
            f"{result['scenario']:<22}"
            f"{inserted_delta:>15.2f}%"
            f"{waiting_delta:>15.2f}%"
            f"{queue_delta:>15.2f}%"
            f"{speed_delta:>15.2f}%"
        )


# =========================================================
# FINAL VALIDATION
# =========================================================

def final_checks(
    results
):

    valid = [

        r

        for r in results

        if r.get(
            "simulation_valid",
            False
        )

    ]

    print()
    print("=" * 70)
    print(
        "FINAL VALIDATION"
    )
    print("=" * 70)
    print()

    # -----------------------------------------------------
    # Scenario execution
    # -----------------------------------------------------

    print(
        "Valid scenarios:",
        len(valid),
        "/",
        len(SCENARIOS)
    )

    if len(valid) == len(SCENARIOS):

        print(
            "[PASS] All 10 scenarios executed."
        )

    else:

        print(
            "[FAIL] Some scenarios failed."
        )

    # -----------------------------------------------------
    # Vehicle demand
    # -----------------------------------------------------

    vehicle_counts = [

        r[
            "vehicles_inserted"
        ]

        for r in valid

    ]

    unique_counts = len(
        set(vehicle_counts)
    )

    print()
    print(
        "Unique vehicle-demand levels:",
        unique_counts
    )

    if unique_counts > 1:

        print(
            "[PASS] Scenario demand differs."
        )

    else:

        print(
            "[WARNING] All scenarios have "
            "the same vehicle count."
        )

    # -----------------------------------------------------
    # Simulation duration
    # -----------------------------------------------------

    valid_duration = all(

        r[
            "simulation_time"
        ] >= SIMULATION_END

        for r in valid

    )

    if valid_duration and valid:

        print(
            "[PASS] All simulations reached "
            f"{SIMULATION_END} seconds."
        )

    else:

        print(
            "[WARNING] Some simulations did "
            "not reach expected duration."
        )

    # -----------------------------------------------------
    # Traffic lights
    # -----------------------------------------------------

    light_counts = [

        r[
            "traffic_light_count"
        ]

        for r in valid

    ]

    if light_counts:

        if len(
            set(light_counts)
        ) == 1:

            print(
                "[PASS] Traffic-light topology "
                "is consistent."
            )

        else:

            print(
                "[WARNING] Traffic-light topology differs."
            )


